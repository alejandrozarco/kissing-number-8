#!/usr/bin/env python3
"""Generate lean/Kissing8/Addition{d}.lean (d = 3..8): the solid Gegenbauer addition identities
    Zg d k (a*a' + w) (a*a + P) (a'*a' + Q)
      = sum_{m <= k} cA d k m * Zg (d+2m) (k-m) a (a*a+P) 1 * Zg (d+2m) (k-m) a' (a'*a'+Q) 1 * Zprev m w P Q
for k <= 6 (Zprev = Zc for d = 3, Zg (d-1) otherwise). The coefficients are solved and every identity is checked with
sympy before it is written; nonnegativity of the coefficients is checked here and again in Lean.
usage: python3 lean/gen/gen_addition8.py [outdir]   (default lean/Kissing8)"""
import os, sys
import sympy as sp

KMAX = 6
a, a2, w, P, Q = sp.symbols("a a2 w P Q")


def Z(d, k, s, p, q):
    """k!-scaled solid Gegenbauer kernel of R^d (d >= 3), solid Chebyshev kernel for d = 2."""
    if d == 2:
        z = [sp.Integer(1), s]
        for j in range(1, k):
            z.append(sp.expand(2 * s * z[j] - p * q * z[j - 1]))
        return z[k]
    z = [sp.Integer(1), (d - 2) * s]
    for j in range(1, k):
        z.append(sp.expand((2 * j + d - 2) * s * z[j] - j * (j + d - 3) * p * q * z[j - 1]))
    return z[k]


def coeffs(d, k):
    lhs = sp.expand(Z(d, k, a * a2 + w, a * a + P, a2 * a2 + Q))
    cs = sp.symbols(f"c0:{k + 1}")
    rhs = sum(cs[m] * Z(d + 2 * m, k - m, a, a * a + P, 1) * Z(d + 2 * m, k - m, a2, a2 * a2 + Q, 1)
              * Z(d - 1, m, w, P, Q) for m in range(k + 1))
    sol = sp.solve(sp.Poly(sp.expand(lhs - rhs), a, a2, w, P, Q).coeffs(), cs, dict=True)
    assert len(sol) == 1, (d, k)
    c = [sol[0][x] for x in cs]
    assert all(x >= 0 for x in c), (d, k, c)
    assert sp.expand(lhs - rhs.subs(dict(zip(cs, c)))) == 0
    return c


def lean_q(x):
    x = sp.Rational(x)
    return str(x.p) if x.q == 1 else f"{x.p}/{x.q}"


def module(d, C):
    prev = "Zc m w P Q" if d == 3 else f"Zg {d - 1} m w P Q"
    imp = "import Kissing8.Kernel" if d == 3 else f"import Kissing8.Addition{d - 1}"
    L = [imp, "",
         f"/-! Solid Gegenbauer addition identities from `ℝ^{d}` to `ℝ^{d - 1}`, degrees `k ≤ {KMAX}`.", "",
         "Generated by `lean/gen/gen_addition8.py` (every identity is first checked with sympy). Do not edit; regenerate.",
         "", f"For `x = (a, y)`, `x' = (a', y')` with `y, y' ∈ ℝ^{d - 1}`, `w = ⟪y, y'⟫`, `P = ‖y‖²`, `Q = ‖y'‖²`:",
         f"`Zg {d} k ⟪x, x'⟫ ‖x‖² ‖x'‖² = ∑_{{m ≤ k}} cA{d} k m · B(a) · B(a') · Z_m(w, P, Q)` with",
         f"`B(a) = Zg ({d} + 2m) (k - m) a ‖x‖² 1` and `Z_m` the kernel of `ℝ^{d - 1}`"
         f"{' (Chebyshev, `Zc`)' if d == 3 else ''}. -/", "",
         "namespace Kissing8", "",
         f"/-- The coefficients of the identities from `ℝ^{d}` (`0` outside `m ≤ k ≤ {KMAX}`). -/",
         f"noncomputable def cA{d} : ℕ → ℕ → ℝ"]
    for k in range(KMAX + 1):
        for m in range(k + 1):
            L.append(f"  | {k}, {m} => {lean_q(C[k][m])}")
    L += ["  | _, _ => 0", "",
          f"theorem cA{d}_nonneg (k m : ℕ) : 0 ≤ cA{d} k m := by", f"  unfold cA{d}", "  split <;> norm_num", ""]
    for k in range(KMAX + 1):
        L += [f"theorem add{d}_{k} (a a' w P Q : ℝ) :",
              f"    Zg {d} {k} (a * a' + w) (a * a + P) (a' * a' + Q) = ∑ m ∈ Finset.range {k + 1},",
              f"      cA{d} {k} m * Zg ({d} + 2 * m) ({k} - m) a (a * a + P) 1 * Zg ({d} + 2 * m) ({k} - m) a' (a' * a' + Q) 1",
              f"        * {prev} := by",
              "  simp only [Finset.sum_range_succ, Finset.sum_range_zero, Nat.reduceAdd, Nat.reduceMul, Nat.reduceSub]",
              f"  simp only [cA{d}, Zg{', Zc' if d == 3 else ''}]",
              "  push_cast", "  ring", ""]
    L.append("end Kissing8")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "Kissing8")
    for d in range(3, 9):
        C = [coeffs(d, k) for k in range(KMAX + 1)]
        open(os.path.join(out, f"Addition{d}.lean"), "w", encoding="utf-8").write(module(d, C))
        print(f"Addition{d}.lean: {sum(len(c) for c in C)} coefficients, all >= 0, identities checked")
