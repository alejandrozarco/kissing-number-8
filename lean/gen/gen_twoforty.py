#!/usr/bin/env python3
"""Generate lean/Kissing8/TwoForty.lean: 240 kissing points of R^8 with integer coordinates.

Construction A of the extended Hamming code [8,4,4] (generator rows 11110000, 00111100, 00001111, 10101010): the
points are the x in Z^8 with (x mod 2) in the code and |x|^2 = 4, i.e. the 240 minimal vectors of sqrt(2) E8:
the 16 vectors +-2 e_i and the 224 vectors with entries +-1 on the support of one of the 14 weight-4 codewords.
Checks: exactly 240 points, all of squared norm 4, minimum pairwise squared distance 4.
The table is emitted as N/CHUNK lists of CHUNK rows; the pairwise check is one `decide +kernel` per block (List.Pairwise),
so that the kernel walks the lists instead of indexing into a 240-row table (which ran out of memory).
usage: python3 lean/gen/gen_twoforty.py [outfile]   (default lean/Kissing8/TwoForty.lean)"""
import itertools, os, sys

N, DIM, CHUNK = 240, 8, 24
GEN = ["11110000", "00111100", "00001111", "10101010"]


def code():
    rows = [tuple(int(c) for c in g) for g in GEN]
    words = set()
    for coef in itertools.product((0, 1), repeat=len(rows)):
        words.add(tuple(sum(c * r[k] for c, r in zip(coef, rows)) % 2 for k in range(DIM)))
    return words


def points():
    C = code()
    assert len(C) == 16, len(C)
    weights = sorted(sum(w) for w in C)
    assert weights == [0] + [4] * 14 + [8], weights
    pts = []
    for k in range(DIM):                                    # +-2 e_k
        for s in (2, -2):
            pts.append(tuple(s if m == k else 0 for m in range(DIM)))
    for w in sorted((w for w in C if sum(w) == 4), reverse=True):   # +-1 on the support of a weight-4 word
        supp = [m for m in range(DIM) if w[m]]
        for signs in itertools.product((1, -1), repeat=4):
            x = [0] * DIM
            for m, s in zip(supp, signs):
                x[m] = s
            pts.append(tuple(x))
    # independent check against the definition: all x in {-2..2}^8 with x mod 2 in C and |x|^2 = 4
    direct = {x for x in itertools.product(range(-2, 3), repeat=DIM)
              if sum(v * v for v in x) == 4 and tuple(v % 2 for v in x) in C}
    assert len(pts) == len(set(pts)) == N and set(pts) == direct
    return pts


def check(pts):
    assert all(sum(v * v for v in x) == 4 for x in pts)
    dmin = min(sum((a - b) ** 2 for a, b in zip(x, y)) for x, y in itertools.combinations(pts, 2))
    assert dmin == 4, dmin
    print(f"{len(pts)} points, all of squared norm 4, minimum pairwise squared distance {dmin}")


def sq_sum(f, indent=None):
    """The sum of f(0), ..., f(7); with `indent`, broken after the fourth term."""
    if indent is None:
        return " + ".join(f(k) for k in range(DIM))
    half = DIM // 2
    return (" + ".join(f(k) for k in range(half)) + " +\n" + " " * indent
            + " + ".join(f(k) for k in range(half, DIM)))


def emit(pts):
    nb = N // CHUNK
    assert nb * CHUNK == N
    sep_sum = sq_sum(lambda k: f"(x {k} - y {k}) ^ 2", 6)
    norm_sum = sq_sum(lambda k: f"x {k} ^ 2", 6)
    pnorm = sq_sum(lambda k: f"P i {k} ^ 2", 6)

    def pdist(i, j):
        return sq_sum(lambda k: f"(P {i} {k} - P {j} {k}) ^ 2", 6)

    out = [f"""import Mathlib

/-!
# Two hundred forty kissing balls in `ℝ⁸`

Two hundred forty points with integer coordinates, each at distance exactly `2` from the origin and at distance at
least `2` from each other. They are the minimal vectors of `√2 E₈`, by Construction A from the extended Hamming code
`[8,4,4]` (generator rows `11110000`, `00111100`, `00001111`, `10101010`): the `x ∈ ℤ⁸` with `x mod 2` in the code
and `‖x‖² = 4`. These are the sixteen points `±2 eᵢ` and the two hundred twenty-four points with entries `±1` on the
support of one of the fourteen codewords of weight `4` (and `0` elsewhere). Everything is checked in integer
arithmetic.

The table is stored as {nb} lists `rows0`, …, `rows{nb - 1}` of {CHUNK} rows each, and `P i` is the `i`-th row of their
concatenation `rows`. The kernel checks the norms on the list, and the separation as `List.Pairwise` of the list, one
block of rows at a time (`rows_sep0`, …), walking the lists instead of indexing into them: indexing costs time and
memory linear in the index, which is too much for the `240 · 239` pairs.

Generated by `lean/gen/gen_twoforty.py`, which first checks the count, the norms and the minimum distance.
Do not edit; regenerate.
-/

namespace Kissing8
namespace TwoForty
"""]
    for c in range(nb):
        blk = ",\n    ".join("![" + ", ".join(str(v) for v in x) + "]" for x in pts[c * CHUNK:(c + 1) * CHUNK])
        out.append(f"""
/-- The rows `{c * CHUNK} ≤ i < {(c + 1) * CHUNK}` of the table. -/
def rows{c} : List (Fin {DIM} → ℤ) :=
  [{blk}]
""")
    out.append(f"""
/-- The rows from `{(nb - 1) * CHUNK}` on. -/
def rowsFrom{nb - 1} : List (Fin {DIM} → ℤ) :=
  rows{nb - 1}
""")
    for c in reversed(range(nb - 1)):
        out.append(f"""
/-- The rows from `{c * CHUNK}` on. -/
def rowsFrom{c} : List (Fin {DIM} → ℤ) :=
  rows{c} ++ rowsFrom{c + 1}
""")
    out.append(f"""
/-- The table: the {N} points, in order. -/
def rows : List (Fin {DIM} → ℤ) :=
  rowsFrom0

theorem rows_length : rows.length = {N} := by
  decide +kernel

/-- The coordinates of the `i`-th point. -/
def P (i : Fin {N}) : Fin {DIM} → ℤ :=
  rows[i.val]'(by rw [rows_length]; exact i.isLt)

theorem P_mem (i : Fin {N}) : P i ∈ rows :=
  List.getElem_mem _

theorem rows_norm : ∀ x ∈ rows, {norm_sum} = 4 := by
  decide +kernel

theorem P_norm : ∀ i, {pnorm} = 4 :=
  fun i => rows_norm (P i) (P_mem i)

/-- `x` and `y` are at squared distance at least `4`. -/
abbrev Sep (x y : Fin {DIM} → ℤ) : Prop :=
  4 ≤ {sep_sum}

instance : DecidableRel Sep := fun _ _ => Int.decLe _ _
""")
    for c in range(nb):
        if c < nb - 1:
            stmt = f"rows{c}.Pairwise Sep ∧ ∀ x ∈ rows{c}, ∀ y ∈ rowsFrom{c + 1}, Sep x y"
            doc = f"The pairs within the block `rows{c}`, and from it to the later blocks."
        else:
            stmt = f"rows{c}.Pairwise Sep"
            doc = f"The pairs within the last block `rows{c}`."
        out.append(f"""
/-- {doc} -/
theorem rows_sep{c} : {stmt} := by
  decide +kernel
""")

    out.append(f"""
theorem rowsFrom_sep{nb - 1} : rowsFrom{nb - 1}.Pairwise Sep :=
  rows_sep{nb - 1}
""")
    for c in reversed(range(nb - 1)):
        out.append(f"""
theorem rowsFrom_sep{c} : rowsFrom{c}.Pairwise Sep :=
  (List.pairwise_append (l₁ := rows{c}) (l₂ := rowsFrom{c + 1})).mpr
    ⟨rows_sep{c}.1, rowsFrom_sep{c + 1}, rows_sep{c}.2⟩
""")
    sym = (", ".join(f"e (P i {k}) (P j {k})" for k in range(DIM // 2)) + ",\n      "
           + ", ".join(f"e (P i {k}) (P j {k})" for k in range(DIM // 2, DIM)))
    lt_i = "(by rw [rows_length]; exact i.isLt)"
    lt_j = "(by rw [rows_length]; exact j.isLt)"
    out.append(f"""
theorem rows_sep : rows.Pairwise Sep :=
  rowsFrom_sep0

theorem P_sep : ∀ i j, i ≠ j →
    4 ≤ {pdist("i", "j")} := by
  intro i j hij
  have h := List.pairwise_iff_getElem.mp rows_sep
  rcases Nat.lt_or_gt_of_ne (Fin.val_ne_of_ne hij) with hlt | hlt
  · exact h i.val j.val {lt_i} {lt_j} hlt
  · have h2 : 4 ≤ {pdist("j", "i").replace(chr(10) + " " * 6, chr(10) + " " * 8)} :=
      h j.val i.val {lt_j} {lt_i} hlt
    have e : ∀ a b : ℤ, (a - b) ^ 2 = (b - a) ^ 2 := fun a b => by ring
    rw [{sym}]
    exact h2

/-- The `i`-th point. -/
noncomputable def pt (i : Fin {N}) : EuclideanSpace ℝ (Fin {DIM}) :=
  WithLp.toLp 2 fun k => (P i k : ℝ)

/-- A point of `ℝ⁸` whose squared coordinates sum to `4` has norm `2`. -/
lemma norm_eq_two {{x : EuclideanSpace ℝ (Fin {DIM})}}
    (h : {sq_sum(lambda k: f"x {k} ^ 2", 8)} = 4) : ‖x‖ = 2 := by
  have hs : ‖x‖ ^ 2 = 4 := by
    rw [EuclideanSpace.real_norm_sq_eq, Fin.sum_univ_eight]
    exact h
  nlinarith [norm_nonneg x]

/-- Two points of `ℝ⁸` whose squared coordinate differences sum to at least `4` are at least `2` apart. -/
lemma two_le_dist {{x y : EuclideanSpace ℝ (Fin {DIM})}}
    (h : 4 ≤ {sq_sum(lambda k: f"(x {k} - y {k}) ^ 2", 8)}) :
    2 ≤ dist x y := by
  rw [dist_eq_norm]
  have hs : 4 ≤ ‖x - y‖ ^ 2 := by
    rw [EuclideanSpace.real_norm_sq_eq, Fin.sum_univ_eight]
    simpa only [PiLp.sub_apply] using h
  nlinarith [norm_nonneg (x - y)]

theorem norm_pt (i : Fin {N}) : ‖pt i‖ = 2 := by
  apply norm_eq_two
  simp only [pt, PiLp.toLp_apply]
  exact_mod_cast P_norm i

theorem dist_pt (i j : Fin {N}) (hij : i ≠ j) : 2 ≤ dist (pt i) (pt j) := by
  apply two_le_dist
  simp only [pt, PiLp.toLp_apply]
  exact_mod_cast P_sep i j hij

theorem pt_injective : Function.Injective pt := by
  intro i j h
  by_contra hij
  have := dist_pt i j hij
  rw [h, dist_self] at this
  norm_num at this

end TwoForty
end Kissing8
""")
    return "".join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "Kissing8", "TwoForty.lean")
    pts = points()
    check(pts)
    with open(path, "w") as f:
        f.write(emit(pts))
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
